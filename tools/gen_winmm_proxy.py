"""Generate the winmm.dll proxy export table from the system winmm.dll.

Writes:
  src/proxy/winmm.def          EXPORTS that map each winmm name/ordinal to a local stub
  src/proxy/winmm_exports.inc  X-macro list: WINMM_EXPORT(index, "name")  (name is "" for ordinal-only)

Each stub is a naked jmp through a pointer table that proxy.cpp fills from the real
%SystemRoot%\\SysWOW64\\winmm.dll at load. Only export names and ordinals are taken from the
system DLL; nothing else is copied.

Usage: python tools/gen_winmm_proxy.py [path-to-32-bit-winmm.dll]
"""
import os
import sys

import pefile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.environ['SystemRoot'], 'SysWOW64', 'winmm.dll')

pe = pefile.PE(src, fast_load=True)
pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
if pe.FILE_HEADER.Machine != 0x14c:
    sys.exit(f'{src} is not a 32-bit DLL')

symbols = sorted(pe.DIRECTORY_ENTRY_EXPORT.symbols, key=lambda s: s.ordinal)
out_dir = os.path.join(ROOT, 'src', 'proxy')
os.makedirs(out_dir, exist_ok=True)

with open(os.path.join(out_dir, 'winmm.def'), 'w', newline='\n') as f:
    f.write('; Generated by tools/gen_winmm_proxy.py - do not edit.\n')
    f.write('LIBRARY winmm\nEXPORTS\n')
    for i, s in enumerate(symbols):
        if s.name:
            f.write(f'    {s.name.decode()}=winmm_stub_{i} @{s.ordinal}\n')
        else:
            f.write(f'    winmm_ord_{s.ordinal}=winmm_stub_{i} @{s.ordinal} NONAME\n')

with open(os.path.join(out_dir, 'winmm_exports.inc'), 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_winmm_proxy.py - do not edit.\n')
    f.write('// WINMM_EXPORT(index, name, ordinal); name is "" for ordinal-only exports.\n')
    for i, s in enumerate(symbols):
        name = s.name.decode() if s.name else ''
        f.write(f'WINMM_EXPORT({i}, "{name}", {s.ordinal})\n')
    f.write(f'#define WINMM_EXPORT_COUNT {len(symbols)}\n')

print(f'{len(symbols)} exports from {src}')
